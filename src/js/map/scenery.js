  function cloudTexture(seed) {
    const w = 256, h = 128, c = document.createElement('canvas'); c.width = w; c.height = h;
    const ctx = c.getContext('2d'); const r = makeRng(seed);
    const n = 10 + Math.floor(r() * 6);
    for (let i = 0; i < n; i++) {
      const cx = w * 0.18 + r() * w * 0.64, cy = h * 0.42 + r() * h * 0.3, rad = h * (0.17 + r() * 0.22);
      const g = ctx.createRadialGradient(cx, cy, 0, cx, cy, rad);
      g.addColorStop(0, 'rgba(255,255,255,0.95)');
      g.addColorStop(0.5, 'rgba(255,252,253,0.6)');
      g.addColorStop(1, 'rgba(255,255,255,0)');
      ctx.fillStyle = g; ctx.fillRect(cx - rad, cy - rad, rad * 2, rad * 2);
    }
    ctx.globalCompositeOperation = 'source-atop';
    const sh = ctx.createLinearGradient(0, h * 0.3, 0, h);
    sh.addColorStop(0, 'rgba(255,255,255,0)'); sh.addColorStop(1, 'rgba(205,170,200,0.6)');
    ctx.fillStyle = sh; ctx.fillRect(0, 0, w, h);
    ctx.globalCompositeOperation = 'source-over';
    const tex = new THREE.CanvasTexture(c); tex.colorSpace = THREE.SRGBColorSpace;
    return tex;
  }

  // distant floating island: rock chunk with flat top, spikes below, tiny buildings. One merged mesh, vertex colours.
  function skyIslandGeometry(rng, R, hazeColor, hazeAmt) {
    const geos = [];
    const rockCol = new THREE.Color(0x5b4f47).lerp(hazeColor, hazeAmt);
    const rockDark = new THREE.Color(0x46403c).lerp(hazeColor, hazeAmt * 0.9);
    const N = 11, noise = periodicNoise(rng, 4);
    const rings = [
      { y: 0, k: 1.0 }, { y: -R * 0.22, k: 1.08 }, { y: -R * 0.55, k: 0.78 }, { y: -R * 0.95, k: 0.42 }, { y: -R * 1.3, k: 0.12 }
    ];
    const pts = rings.map((rg, ri) => {
      const arr = [];
      for (let i = 0; i < N; i++) {
        const th = i / N * Math.PI * 2;
        const rad = R * rg.k * (1 + 0.28 * noise(th + ri * 0.7)) * (0.92 + rng() * 0.16);
        arr.push(new THREE.Vector3(Math.cos(th) * rad, rg.y + (ri ? (rng() - 0.5) * R * 0.08 : 0), Math.sin(th) * rad));
      }
      return arr;
    });
    const tri = [];
    function pushTri(a, b, c) { tri.push(a.x, a.y, a.z, b.x, b.y, b.z, c.x, c.y, c.z); }
    // top cap (fan, faces up)
    const top = new THREE.Vector3(0, 0, 0);
    for (let i = 0; i < N; i++) pushTri(top, pts[0][(i + 1) % N], pts[0][i]);
    for (let r = 0; r < rings.length - 1; r++) {
      for (let i = 0; i < N; i++) {
        const a = pts[r][i], b = pts[r][(i + 1) % N], c = pts[r + 1][(i + 1) % N], d = pts[r + 1][i];
        pushTri(a, b, c); pushTri(a, c, d);
      }
    }
    const bottom = new THREE.Vector3((rng() - 0.5) * R * 0.2, -R * 1.5, (rng() - 0.5) * R * 0.2);
    const last = pts[rings.length - 1];
    for (let i = 0; i < N; i++) pushTri(last[i], last[(i + 1) % N], bottom);
    const rock = new THREE.BufferGeometry();
    rock.setAttribute('position', new THREE.BufferAttribute(new Float32Array(tri), 3));
    rock.computeVertexNormals();
    // colour: top faces lighter rock, sides darker
    const nrm = rock.attributes.normal, cnt = rock.attributes.position.count, colArr = new Float32Array(cnt * 3);
    for (let i = 0; i < cnt; i++) {
      const up = Math.max(0, nrm.getY(i));
      const c = rockDark.clone().lerp(rockCol, up);
      colArr[i * 3] = c.r; colArr[i * 3 + 1] = c.g; colArr[i * 3 + 2] = c.b;
    }
    rock.setAttribute('color', new THREE.BufferAttribute(colArr, 3));
    rock.setAttribute('uv', new THREE.BufferAttribute(new Float32Array(cnt * 2), 2));
    geos.push(rock);
    // hanging spikes
    const nsp = 3 + rng.int(0, 4);
    for (let i = 0; i < nsp; i++) {
      const th = rng() * Math.PI * 2, rr = R * rng.range(0.15, 0.7);
      const sh = R * rng.range(0.5, 1.1), sr = R * rng.range(0.06, 0.13);
      const g = new THREE.ConeGeometry(sr, sh, 5, 1);
      xf(g, Math.cos(th) * rr, -R * 0.45 - sh / 2, Math.sin(th) * rr, rng() * 6.28, Math.PI + (rng() - 0.5) * 0.25, (rng() - 0.5) * 0.25);
      addColorAttr(g.toNonIndexed(), rockDark);
      const gg = g.toNonIndexed(); gg.computeVertexNormals(); addColorAttr(gg, rockDark); geos.push(gg);
    }
    // tiny buildings on top
    const nb = rng.chance(0.15) ? 0 : rng.int(3, 9);
    const plasters = [0xe9dcc3, 0xf1ece0, 0xd9a07f, 0xd8b56a, 0xd6a3a0];
    for (let i = 0; i < nb; i++) {
      const th = rng() * Math.PI * 2, rr = R * rng.range(0, 0.55);
      const bw = rng.range(3, 7), bd = rng.range(3, 7), bh = rng.range(3, 9), ry = rng() * Math.PI;
      const wall = new THREE.Color(rng.pick(plasters)).lerp(hazeColor, hazeAmt);
      const roofc = new THREE.Color(0xa8563c).lerp(hazeColor, hazeAmt);
      const bx = Math.cos(th) * rr, bz = Math.sin(th) * rr;
      const b = new THREE.BoxGeometry(bw, bh, bd); xf(b, bx, bh / 2 - 0.3, bz, ry); addColorAttr(b, wall); geos.push(b);
      const roof = new THREE.ConeGeometry(Math.max(bw, bd) * 0.72, Math.min(bw, bd) * 0.45, 4, 1);
      xf(roof, bx, bh - 0.3 + Math.min(bw, bd) * 0.225, bz, ry + Math.PI / 4); const rg = roof.toNonIndexed(); rg.computeVertexNormals(); addColorAttr(rg, roofc); geos.push(rg);
    }
    if (nb > 4 && rng.chance(0.5)) { // a little tower
      const th = rng() * Math.PI * 2, rr = R * rng.range(0.1, 0.4), tw = rng.range(2.5, 3.5), tH = rng.range(12, 20);
      const t = new THREE.BoxGeometry(tw, tH, tw); xf(t, Math.cos(th) * rr, tH / 2 - 0.3, Math.sin(th) * rr);
      addColorAttr(t, new THREE.Color(0x9c4b3a).lerp(hazeColor, hazeAmt)); geos.push(t);
      const cap = new THREE.ConeGeometry(tw * 0.8, tw * 1.2, 4, 1); xf(cap, Math.cos(th) * rr, tH - 0.3 + tw * 0.6, Math.sin(th) * rr, Math.PI / 4);
      const cg = cap.toNonIndexed(); cg.computeVertexNormals(); addColorAttr(cg, new THREE.Color(0x3c8a6e).lerp(hazeColor, hazeAmt)); geos.push(cg);
    }
    return mergeGeos(geos.map(g => g.index ? g.toNonIndexed() : g));
  }

  S.buildSky = function (scene, renderer) {
    const rng = makeRng(20240613);
    const horizon = new THREE.Color(SKY.horizon);
    scene.background = horizon.clone();
    scene.fog = new THREE.Fog(horizon.clone(), 60, 260);

    const group = new THREE.Group(); group.name = 'sky';
    scene.add(group);

    // -- gradient dome (follows the camera, drawn first, ignores depth so its radius does not matter)
    const sunDir = new THREE.Vector3(-0.62, 0.30, 0.72).normalize(); // toward the sun: low south-west
    const uniforms = {
      horizon: { value: horizon.clone() }, mid: { value: new THREE.Color(SKY.mid) }, zenith: { value: new THREE.Color(SKY.zenith) },
      below: { value: new THREE.Color(SKY.below) }, deep: { value: new THREE.Color(SKY.deep) },
      sunColor: { value: new THREE.Color(SKY.sun) }, glowColor: { value: new THREE.Color(SKY.glow) },
      sunDir: { value: sunDir.clone() }
    };
    const skyMat = new THREE.ShaderMaterial({ uniforms, vertexShader: SKY_VERT, fragmentShader: SKY_FRAG, side: THREE.BackSide, depthWrite: false, depthTest: false, fog: false });
    const dome = new THREE.Mesh(new THREE.SphereGeometry(40, 32, 20), skyMat);
    dome.name = 'skyDome'; dome.renderOrder = -1000; dome.frustumCulled = false;
    dome.matrixAutoUpdate = true;
    const camPos = new THREE.Vector3();
    dome.onBeforeRender = function (r, sc, camera) {
      camera.getWorldPosition(camPos);
      dome.position.copy(camPos);
      dome.updateMatrixWorld(true);
    };
    group.add(dome);

    // -- clouds (sprites, no fog: they carry their own haze tint)
    const cloudTex = [cloudTexture(11), cloudTexture(23), cloudTexture(37)];
    const clouds = [];
    const cloudGroup = new THREE.Group(); cloudGroup.name = 'clouds'; group.add(cloudGroup);
    function addCloud(theta, dist, y, w, opacity, tint) {
      const m = new THREE.SpriteMaterial({ map: rng.pick(cloudTex), transparent: true, opacity: opacity, depthWrite: false, fog: false, color: tint });
      const sp = new THREE.Sprite(m);
      sp.position.set(Math.cos(theta) * dist, y, Math.sin(theta) * dist);
      sp.scale.set(w, w * 0.5, 1);
      sp.userData = { theta, dist, y0: y, speed: rng.range(0.004, 0.009), bob: rng() * 6.28 };
      cloudGroup.add(sp); clouds.push(sp);
      return sp;
    }
    for (let i = 0; i < 9; i++) { // low cloud banks below the island rim
      const th = i / 9 * Math.PI * 2 + rng.range(-0.25, 0.25);
      addCloud(th, rng.range(170, 300), rng.range(-70, -30), rng.range(260, 420), 0.92, 0xf6ecf2);
    }
    for (let i = 0; i < 8; i++) { // cumulus around the horizon
      const th = i / 8 * Math.PI * 2 + rng.range(-0.3, 0.3) + 0.4;
      addCloud(th, rng.range(260, 380), rng.range(-5, 45), rng.range(120, 220), 0.85, 0xfaf1f5);
    }
    for (let i = 0; i < 4; i++) { // a few high wisps
      addCloud(rng() * 6.28, rng.range(280, 380), rng.range(70, 130), rng.range(160, 240), 0.55, 0xf3e6ee);
    }

    // -- distant floating islands
    const islandMat = new THREE.MeshStandardMaterial({ vertexColors: true, roughness: 0.95, metalness: 0, fog: false });
    islandMat.flatShading = true;
    const islands = [];
    const nIsl = 9;
    for (let i = 0; i < nIsl; i++) {
      const th = i / nIsl * Math.PI * 2 + rng.range(-0.2, 0.2) + 0.15;
      const dist = rng.range(170, 380);
      const haze = 0.42 + 0.4 * (dist - 170) / 210;
      const R = rng.range(16, 44) * (dist > 300 ? 1.3 : 1);
      const geo = skyIslandGeometry(rng, R, horizon, haze);
      const mesh = new THREE.Mesh(geo, islandMat);
      const y = rng.chance(0.5) ? rng.range(-45, -10) : rng.range(10, 70);
      mesh.position.set(Math.cos(th) * dist, y, Math.sin(th) * dist);
      mesh.rotation.y = rng() * 6.28;
      mesh.userData = { theta: th, dist, y0: y, bobAmp: rng.range(1.2, 3), bobRate: rng.range(0.04, 0.09), phase: rng() * 6.28, drift: rng.range(0.0008, 0.0018) };
      mesh.frustumCulled = true;
      group.add(mesh); islands.push(mesh);
    }

    let t = 0;
    const api = {
      group, dome, clouds, islands, sunDir,
      setSunDirection(dir) { if (dir) { sunDir.copy(dir).normalize(); uniforms.sunDir.value.copy(sunDir); } },
      update(dt, dir) {
        dt = Math.min(dt || 0, 0.1); t += dt;
        if (dir && dir.isVector3) api.setSunDirection(dir);
        for (const c of clouds) {
          const u = c.userData; u.theta += u.speed * dt;
          c.position.set(Math.cos(u.theta) * u.dist, u.y0 + Math.sin(t * 0.05 + u.bob) * 3, Math.sin(u.theta) * u.dist);
        }
        for (const m of islands) {
          const u = m.userData; u.theta += u.drift * dt;
          m.position.set(Math.cos(u.theta) * u.dist, u.y0 + Math.sin(t * u.bobRate + u.phase) * u.bobAmp, Math.sin(u.theta) * u.dist);
        }
        for (let i = 0; i < _animated.length; i++) _animated[i](dt, t);
      }
    };
    return api;
  };

