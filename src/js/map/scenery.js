  // ------------------------------------------------------------------ random / noise
  function makeRng(seed) {
    let a = (seed >>> 0) || 1;
    const r = function () {
      a = (a + 0x6D2B79F5) >>> 0;
      let t = a;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
    r.range = (lo, hi) => lo + (hi - lo) * r();
    r.int = (lo, hi) => Math.floor(lo + (hi - lo + 1) * r());
    r.pick = (arr) => arr[Math.floor(r() * arr.length) % arr.length];
    r.chance = (p) => r() < p;
    return r;
  }
  // smooth 2π-periodic noise in [-1,1]
  function periodicNoise(rng, octaves) {
    const terms = [];
    let norm = 0;
    for (let k = 1; k <= octaves; k++) { terms.push({ f: k, a: 1 / k, p: rng() * Math.PI * 2 }); norm += 1 / k; }
    return function (theta) {
      let v = 0;
      for (let i = 0; i < terms.length; i++) v += terms[i].a * Math.sin(terms[i].f * theta + terms[i].p);
      return v / norm;
    };
  }

