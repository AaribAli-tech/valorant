  // ------------------------------------------------------------------ geometry helpers
  const _m4 = new THREE.Matrix4(), _q = new THREE.Quaternion(), _e = new THREE.Euler(), _v = new THREE.Vector3(), _sc = new THREE.Vector3();
  // apply position / rotation(YXZ order: ry first) / scale to a geometry in place
  function xf(geo, x, y, z, ry, rx, rz, s) {
    _e.set(rx || 0, ry || 0, rz || 0, 'YXZ');
    _q.setFromEuler(_e);
    if (Array.isArray(s)) _sc.set(s[0], s[1], s[2]); else _sc.set(s || 1, s || 1, s || 1);
    _v.set(x || 0, y || 0, z || 0);
    _m4.compose(_v, _q, _sc);
    geo.applyMatrix4(_m4);
    return geo;
  }
  // BoxGeometry with world-scaled UVs (metres / 2) or per-face 0..1 ('face')
  function boxGeo(w, h, d, uvMode) {
    const g = new THREE.BoxGeometry(w, h, d);
    if (uvMode !== 'face') {
      const uv = g.attributes.uv;
      const spans = [[d, h], [d, h], [w, d], [w, d], [w, h], [w, h]];
      for (let f = 0; f < 6; f++) {
        const su = spans[f][0] / 2, sv = spans[f][1] / 2;
        for (let i = 0; i < 4; i++) { const k = f * 4 + i; uv.setXY(k, uv.getX(k) * su, uv.getY(k) * sv); }
      }
      uv.needsUpdate = true;
    }
    return g;
  }
  function planeGeo(w, h) {
    const g = new THREE.PlaneGeometry(w, h);
    const uv = g.attributes.uv;
    for (let i = 0; i < uv.count; i++) uv.setXY(i, uv.getX(i) * w / 2, uv.getY(i) * h / 2);
    return g;
  }
  function cylGeo(rt, rb, h, seg, openEnded) {
    const g = new THREE.CylinderGeometry(rt, rb, h, seg || 12, 1, !!openEnded);
    const uv = g.attributes.uv, circ = Math.PI * (rt + rb);
    const sideCount = 2 * ((seg || 12) + 1);
    for (let i = 0; i < sideCount && i < uv.count; i++) uv.setXY(i, uv.getX(i) * circ / 2, uv.getY(i) * h / 2);
    return g;
  }
  function addColorAttr(geo, hexOrColor) {
    const c = hexOrColor.isColor ? hexOrColor : new THREE.Color(hexOrColor);
    const n = geo.attributes.position.count, arr = new Float32Array(n * 3);
    for (let i = 0; i < n; i++) { arr[i * 3] = c.r; arr[i * 3 + 1] = c.g; arr[i * 3 + 2] = c.b; }
    geo.setAttribute('color', new THREE.BufferAttribute(arr, 3));
    return geo;
  }
  // Merge a list of BufferGeometries (position/normal/uv[/color]) into one. Indexed when all inputs are.
  function mergeGeos(list) {
    if (!list || !list.length) return null;
    let indexed = true, hasColor = false;
    for (const g of list) { if (!g.index) indexed = false; if (g.attributes.color) hasColor = true; }
    let vCount = 0, iCount = 0;
    const geos = [];
    for (let g of list) {
      if (!indexed && g.index) g = g.toNonIndexed();
      if (!g.attributes.normal) g.computeVertexNormals();
      vCount += g.attributes.position.count;
      if (indexed) iCount += g.index.count;
      geos.push(g);
    }
    const pos = new Float32Array(vCount * 3), nor = new Float32Array(vCount * 3), uv = new Float32Array(vCount * 2);
    const col = hasColor ? new Float32Array(vCount * 3) : null;
    const idx = indexed ? (vCount > 65535 ? new Uint32Array(iCount) : new Uint16Array(iCount)) : null;
    let vo = 0, io = 0;
    for (const g of geos) {
      const n = g.attributes.position.count;
      pos.set(g.attributes.position.array.subarray(0, n * 3), vo * 3);
      nor.set(g.attributes.normal.array.subarray(0, n * 3), vo * 3);
      if (g.attributes.uv) uv.set(g.attributes.uv.array.subarray(0, n * 2), vo * 2);
      if (hasColor) {
        if (g.attributes.color) col.set(g.attributes.color.array.subarray(0, n * 3), vo * 3);
        else col.fill(1, vo * 3, (vo + n) * 3);
      }
      if (indexed) { const ia = g.index.array; for (let i = 0; i < ia.length; i++) idx[io + i] = ia[i] + vo; io += ia.length; }
      vo += n;
    }
    const out = new THREE.BufferGeometry();
    out.setAttribute('position', new THREE.BufferAttribute(pos, 3));
    out.setAttribute('normal', new THREE.BufferAttribute(nor, 3));
    out.setAttribute('uv', new THREE.BufferAttribute(uv, 2));
    if (hasColor) out.setAttribute('color', new THREE.BufferAttribute(col, 3));
    if (indexed) out.setIndex(new THREE.BufferAttribute(idx, 1));
    return out;
  }
  S._mergeGeos = mergeGeos;

  // Parts collector: add transformed geometries per material, then build merged meshes into a group.
  function Parts() { this.map = new Map(); this.list = []; }
  Parts.prototype.add = function (geo, material, x, y, z, ry, rx, rz, s) {
    xf(geo, x, y, z, ry, rx, rz, s);
    let arr = this.map.get(material);
    if (!arr) { arr = []; this.map.set(material, arr); this.list.push(material); }
    arr.push(geo);
    return geo;
  };
  Parts.prototype.build = function (group, shadows) {
    for (const m of this.list) {
      const g = mergeGeos(this.map.get(m));
      if (!g) continue;
      const mesh = new THREE.Mesh(g, m);
      if (shadows !== false) { mesh.castShadow = true; mesh.receiveShadow = true; }
      group.add(mesh);
    }
    return group;
  };
  S._Parts = Parts;

